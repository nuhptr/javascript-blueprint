/**
 * Kalikan dua angka dan kembalikan hasilnya.
 *
 * @param {number} p1 Angka pertama.
 * @param {number} p2 Angka kedua.
 * @returns {number} Hasil perkalian p1 dan p2.
 */
function calculation(p1, p2) {
    return p1 * p2
}

/** Panggil calculation dengan 4 dan 3; hasil perkaliannya adalah 12. */
let calc = calculation(4, 3)
/** Tampilkan nilai yang dikembalikan oleh calculation. */
console.log(calc)
