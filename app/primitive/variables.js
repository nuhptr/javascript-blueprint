/**
 * Variabel adalah tempat untuk menyimpan nilai agar bisa digunakan lagi.
 * Nama variabel sebaiknya menjelaskan nilai yang disimpan.
 */

/**
 * let membuat variabel yang nilainya bisa diganti.
 * Jika belum diberi nilai, isinya adalah undefined.
 */
let userName
console.log(userName)

userName = "anmastery"
console.log(userName)

userName = "Belajar JavaScript"
console.log(userName)

/**
 * const membuat variabel yang tidak bisa diberi nilai baru.
 * Gunakan const jika nilainya tidak perlu diganti.
 */
const channelName = "anmastery"
console.log(channelName)
