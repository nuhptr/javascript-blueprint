/**
 * Challenge:
 * Use two numbers to try addition, subtraction, multiplication,
 * division, remainder, and exponentiation.
 * Print the result of each operation to the console.
 */

/**
 * Angka pertama yang digunakan dalam operasi aritmetika.
 */
let firstNumber = 21

/**
 * Angka kedua yang digunakan dalam operasi aritmetika.
 */
let secondNumber = 7

/**
 * Menjumlahkan kedua angka.
 */
console.log(firstNumber + secondNumber)

/**
 * Mengurangkan angka kedua dari angka pertama.
 */
console.log(firstNumber - secondNumber)

/**
 * Mengalikan kedua angka.
 */
console.log(firstNumber * secondNumber)

/**
 * Membagi angka pertama dengan angka kedua.
 */
console.log(firstNumber / secondNumber)

/**
 * Menghitung sisa pembagian angka pertama dengan angka kedua.
 */
console.log(firstNumber % secondNumber)

/**
 * Memangkatkan angka pertama dengan angka kedua.
 */
console.log(firstNumber ** secondNumber)
