/**
 * Challenge:
 * Use while to print a name 100 times.
 * Start counting at 10 and add 1 after each iteration.
 */

/**
 * Mulai menghitung dari 10.
 */
let i = 10

/**
 * Selama i kurang dari 110, tampilkan nama.
 * i++ menambah hitungan 1 setiap kali agar perulangan berhenti.
 */
while (i < 110) {
    console.log("anmastery developer")
    i++
}
