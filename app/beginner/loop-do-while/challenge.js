/**
 * Hitungan dimulai dari 20.
 */
let i = 20

/**
 * do...while menjalankan kode sekali terlebih dahulu.
 * Setelah itu, i bertambah 1 dan kode diulang selama i kurang dari 420.
 * Dengan begitu, nama dicetak 400 kali, dari hitungan 20 sampai 419.
 */
do {
    console.log("anmastery developer")
    i++
} while (i < 420)
