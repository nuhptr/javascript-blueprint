/**
 * `const` membuat deklarasi yang tidak dapat diberi nilai ulang.
 * Karena nilainya bertipe angka (primitif), nilainya tidak dapat diubah.
 */
const randomNumber = 10200

/**
 * Konstanta untuk menyimpan angka favorit.
 * Nilainya harus ditentukan saat deklarasi dan tidak dapat diberi nilai ulang.
 */
const favNumber = 21

/**
 * Variabel angka yang dapat berubah nilainya.
 */
let num = 2

/**
 * Menjumlahkan dua angka.
 * Hasil: 2 + 2 = 4.
 */
console.log(2 + 2)

/**
 * Mengurangkan angka kedua dari angka pertama.
 * Hasil: 2 - 2 = 0.
 */
console.log(2 - 2)

/**
 * Mengalikan dua angka.
 * Hasil: 2 * 2 = 4.
 */
console.log(2 * 2)

/**
 * Membagi angka pertama dengan angka kedua.
 * Hasil: 2 / 2 = 1.
 */
console.log(2 / 2)

/**
 * Menghitung sisa pembagian.
 * Hasil: 2 % 2 = 0.
 */
console.log(2 % 2)

/**
 * Menghitung hasil pemangkatan.
 * Hasil: 2 ** 2 = 4.
 */
console.log(2 ** 2)

/**
 * Menampilkan nilai num saat ini, lalu menaikkannya satu.
 * Hasil yang ditampilkan: 2; setelah operasi, num bernilai 3.
 */
console.log(num++)

/**
 * Menampilkan nilai num saat ini, lalu menurunkannya satu.
 * Hasil yang ditampilkan: 3; setelah operasi, num bernilai 2.
 */
console.log(num--)
