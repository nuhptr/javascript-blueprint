/**
 * Simpan dua angka favorit ke dalam variabel.
 * Variabel adalah nama untuk menyimpan nilai.
 */
let firstFavNumb = 21
let secondFavNumb = 10

/**
 * Operator perbandingan angka menghasilkan true (benar) atau false (salah).
 * > berarti lebih besar dari. 21 lebih besar dari 10, jadi hasilnya true.
 */
console.log(firstFavNumb > secondFavNumb)

/**
 * < berarti lebih kecil dari. 21 tidak lebih kecil dari 10, jadi hasilnya false.
 */
console.log(firstFavNumb < secondFavNumb)

/**
 * >= berarti lebih besar dari atau sama dengan.
 */
console.log(firstFavNumb >= secondFavNumb)

/**
 * <= berarti lebih kecil dari atau sama dengan.
 */
console.log(firstFavNumb <= secondFavNumb)

/**
 * === memeriksa apakah nilai dan tipe datanya sama.
 */
console.log(firstFavNumb === secondFavNumb)

/**
 * !== memeriksa apakah nilai atau tipe datanya berbeda.
 */
console.log(firstFavNumb !== secondFavNumb)

/**
 * == membandingkan nilai, dan bisa mengubah tipe data sebelum membandingkan.
 * Sebaiknya gunakan === agar perbandingannya lebih jelas.
 */
console.log(firstFavNumb == secondFavNumb)

/**
 * != memeriksa apakah nilainya berbeda, dan bisa mengubah tipe data dahulu.
 * Sebaiknya gunakan !== agar perbandingannya lebih jelas.
 */
console.log(firstFavNumb != secondFavNumb)
