/**
 * Operator perbandingan membandingkan dua nilai.
 * Hasilnya selalu true (benar) atau false (salah).
 */

/**
 * > artinya lebih besar dari.
 * 10 tidak lebih besar dari 10, jadi hasilnya false.
 */
console.log(10 > 10)

/**
 * < artinya lebih kecil dari.
 * 10 tidak lebih kecil dari 10, jadi hasilnya false.
 */
console.log(10 < 10)

/**
 * >= artinya lebih besar dari atau sama dengan.
 * Karena kedua nilainya sama, hasilnya true.
 */
console.log(10 >= 10)

/**
 * <= artinya lebih kecil dari atau sama dengan.
 * Karena kedua nilainya sama, hasilnya true.
 */
console.log(10 <= 10)

/**
 * === membandingkan nilai sekaligus tipe datanya.
 * 10 dan 10 sama-sama number, jadi hasilnya true.
 */
console.log(10 === 10)

/**
 * !== memeriksa apakah nilai atau tipe datanya berbeda.
 * Di contoh ini keduanya sama, jadi hasilnya false.
 */
console.log(10 !== 10)

/**
 * == membandingkan nilai, dan bisa mengubah tipe data terlebih dahulu.
 * Sebaiknya gunakan === agar perbandingannya lebih jelas.
 */
console.log(10 == "10")

/**
 * != memeriksa apakah nilainya berbeda, dan bisa mengubah tipe data terlebih dahulu.
 * Sebaiknya gunakan !== agar perbandingannya lebih jelas.
 */
console.log(10 != "10")
